/** Empty state: identity, corpus size, and real suggestions from the server. */
import { el, formatNumber } from '../lib/dom.js';
import { icons } from '../lib/icons.js';
import type { AppStatus } from '../types.js';

export interface EmptyStateOptions {
  status: AppStatus | null;
  suggestions: string[];
  onSuggestion: (text: string) => void;
  onOpenSources: () => void;
}

const SUGGESTION_ICONS = [icons.sparkle, icons.book, icons.code, icons.database, icons.filter, icons.brain];

export function renderEmptyState(options: EmptyStateOptions): HTMLElement {
  const { status, suggestions } = options;
  const wrapper = el('div', { class: 'empty-state' });

  wrapper.append(el('div', { class: 'empty-state__mark', text: 'ID' }));
  wrapper.append(el('h1', { class: 'empty-state__title', text: 'What should I look into?' }));

  const corpus = status?.knowledge;
  if (corpus && corpus.totalPassages > 0) {
    wrapper.append(
      el(
        'p',
        { class: 'empty-state__subtitle' },
        'I answer from your indexed repositories and cite the exact file and line range behind every claim.',
      ),
    );
  } else {
    wrapper.append(
      el(
        'p',
        { class: 'empty-state__subtitle' },
        'No knowledge source is indexed yet. Add a repository and I will search it — and tell you plainly when something is not covered.',
      ),
    );
  }

  if (corpus && corpus.totalPassages > 0) {
    const corpusBadge = el('div', { class: 'empty-state__corpus' });
    corpusBadge.append(
      dot('ok'),
      el('span', {}, el('strong', { text: formatNumber(corpus.totalPassages) }), ' passages'),
      el('span', { text: '·', style: 'opacity:.4' }),
      el('strong', { text: formatNumber(corpus.totalFiles) }),
      el('span', { text: 'files' }),
      el('span', { text: '·', style: 'opacity:.4' }),
      el('strong', { text: String(corpus.readySources) }),
      el('span', { text: corpus.readySources === 1 ? 'source' : 'sources' }),
    );
    wrapper.append(corpusBadge);
  }

  const items = suggestions.length > 0 ? suggestions.slice(0, 6) : ['What can you do?'];
  const grid = el('div', { class: 'suggestions' });
  items.forEach((text, index) => {
    const button = el('button', { type: 'button', class: 'suggestion', style: `animation-delay:${index * 40}ms` });
    const iconWrap = el('span', { class: 'suggestion__icon' });
    iconWrap.innerHTML = `<svg viewBox="0 0 24 24" width="14" height="14" fill="none" stroke="currentColor" stroke-width="1.75" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">${SUGGESTION_ICONS[index % SUGGESTION_ICONS.length]}</svg>`;
    button.append(iconWrap, el('span', { class: 'suggestion__text', text }));
    button.addEventListener('click', () => options.onSuggestion(text));
    grid.append(button);
  });
  wrapper.append(grid);

  const mode = status?.inference;
  const modeText =
    mode?.mode === 'inference'
      ? `Inference mode: answers are generated by ${mode.model ?? 'the configured provider'} and grounded in retrieved passages.`
      : 'Knowledge mode: answers are composed by an extractive retrieval engine. No language model is used, and nothing is invented.';

  const footnote = el('p', { class: 'empty-state__footnote', text: modeText });
  wrapper.append(footnote);

  if (!corpus || corpus.totalPassages === 0) {
    const button = el('button', { type: 'button', class: 'button button--primary' });
    button.innerHTML = `<svg viewBox="0 0 24 24" width="15" height="15" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">${icons.plus}</svg><span>Add a repository</span>`;
    button.addEventListener('click', options.onOpenSources);
    wrapper.append(button);
  }

  return wrapper;
}

function dot(status: 'ok' | 'warn' | 'error'): HTMLElement {
  return el('span', { class: 'status-dot', 'data-status': status });
}
